$srcFile = "zabbix\templates\zbx_export_templates (1).yaml"
$dstFile = "zabbix\templates\zbx70_aruba_instanton_1930_snmp.yaml"

Write-Host "Reading source template: $srcFile"
$raw = [System.IO.File]::ReadAllText("$pwd\$srcFile", [System.Text.Encoding]::UTF8)

# Normalize all line breaks to `n for reliable regex processing
$content = $raw -replace "\r\n", "`n"

# 1. Update template name and template id
$content = $content -replace "template:\s*'Network Generic Device by SNMP'", "template: 'Aruba Instant On 1930 by SNMP'"
$content = $content -replace "name:\s*'Network Generic Device by SNMP'", "name: 'Aruba Instant On 1930 by SNMP'"

# 2. Update description
$newDesc = @"
description: |
        Template Aruba Instant On 1930 24G 4SFP+ Switch (JL682A and Family)
        
        Optimized with 64-bit High Capacity (ifXTable) counters, 1-minute real-time polling,
        administrative status tracking, and CPU utilization.
        
        MIBs used:
        IF-MIB (ifXTable / ifHighSpeed 64-bit)
        EtherLike-MIB
        SNMPv2-MIB
        HPE-rndMng / STATISTICS-MIB / RADLAN
"@
$content = [System.Text.RegularExpressions.Regex]::Replace($content, "description:\s*\|\n\s+Template Net Network Generic Device[\s\S]*?Generated by official Zabbix template tool `"Templator`"", $newDesc)

# 3. Update all expressions and host references
$content = $content.Replace("/Network Generic Device by SNMP/", "/Aruba Instant On 1930 by SNMP/")
$content = $content.Replace("host: 'Network Generic Device by SNMP'", "host: 'Aruba Instant On 1930 by SNMP'")

# 4. Migrate traffic items to 64-bit High Capacity
# InOctets -> ifHCInOctets
$content = $content.Replace("snmp_oid: '1.3.6.1.2.1.2.2.1.10.{#SNMPINDEX}'", "snmp_oid: '1.3.6.1.2.1.31.1.1.1.6.{#SNMPINDEX}'")
$content = $content.Replace("key: 'net.if.in[ifInOctets.{#SNMPINDEX}]'", "key: 'net.if.in[ifHCInOctets.{#SNMPINDEX}]'")
$content = $content.Replace("net.if.in[ifInOctets.{#SNMPINDEX}]", "net.if.in[ifHCInOctets.{#SNMPINDEX}]")

# OutOctets -> ifHCOutOctets
$content = $content.Replace("snmp_oid: '1.3.6.1.2.1.2.2.1.16.{#SNMPINDEX}'", "snmp_oid: '1.3.6.1.2.1.31.1.1.1.10.{#SNMPINDEX}'")
$content = $content.Replace("key: 'net.if.out[ifOutOctets.{#SNMPINDEX}]'", "key: 'net.if.out[ifHCOutOctets.{#SNMPINDEX}]'")
$content = $content.Replace("net.if.out[ifOutOctets.{#SNMPINDEX}]", "net.if.out[ifHCOutOctets.{#SNMPINDEX}]")

# Speed -> ifHighSpeed with MULTIPLIER 1000000
$content = $content.Replace("snmp_oid: '1.3.6.1.2.1.2.2.1.5.{#SNMPINDEX}'", "snmp_oid: '1.3.6.1.2.1.31.1.1.1.15.{#SNMPINDEX}'")
$content = $content.Replace("key: 'net.if.speed[ifSpeed.{#SNMPINDEX}]'", "key: 'net.if.speed[ifHighSpeed.{#SNMPINDEX}]'")
$content = $content.Replace("net.if.speed[ifSpeed.{#SNMPINDEX}]", "net.if.speed[ifHighSpeed.{#SNMPINDEX}]")

# Add MULTIPLIER 1000000 preprocessing to net.if.speed
$speedOld = "key: 'net.if.speed[ifHighSpeed.{#SNMPINDEX}]'`n              delay: 5m`n              trends: '0'`n              units: bps"
$speedNew = @"
key: 'net.if.speed[ifHighSpeed.{#SNMPINDEX}]'
              delay: 5m
              trends: '0'
              units: bps
              preprocessing:
                - type: MULTIPLIER
                  parameters:
                    - '1000000'
                - type: DISCARD_UNCHANGED_HEARTBEAT
                  parameters:
                    - 1h
"@
$content = $content.Replace($speedOld, $speedNew)

# 5. Set selective delays:
# In/Out traffic to 1m
$content = $content.Replace("key: 'net.if.in[ifHCInOctets.{#SNMPINDEX}]'`n              delay: 3m", "key: 'net.if.in[ifHCInOctets.{#SNMPINDEX}]'`n              delay: 1m")
$content = $content.Replace("key: 'net.if.out[ifHCOutOctets.{#SNMPINDEX}]'`n              delay: 3m", "key: 'net.if.out[ifHCOutOctets.{#SNMPINDEX}]'`n              delay: 1m")

# 6. Update macro {$NET.IF.IFADMINSTATUS.NOT_MATCHES} from ^2$ to CHANGE_IF_NEEDED
$oldAdminMacro = "- macro: '{`$NET.IF.IFADMINSTATUS.NOT_MATCHES}'`n          value: ^2$`n          description: 'Ignore down(2) administrative status'"
$newAdminMacro = "- macro: '{`$NET.IF.IFADMINSTATUS.NOT_MATCHES}'`n          value: CHANGE_IF_NEEDED`n          description: 'Do not ignore down(2) administrative status'"
$content = $content.Replace($oldAdminMacro, $newAdminMacro)

# 7. Add Admin Status item prototype under item_prototypes in net.if.discovery
$adminStatusBlock = @"
            - uuid: REPLACE_ADMIN_STATUS_UUID
              name: 'Interface {#IFNAME}({#IFALIAS}): Administrative status'
              type: SNMP_AGENT
              snmp_oid: '1.3.6.1.2.1.2.2.1.7.{#SNMPINDEX}'
              key: 'net.if.adminstatus[ifAdminStatus.{#SNMPINDEX}]'
              delay: 5m
              valuemap:
                name: 'IF-MIB::ifOperStatus'
              tags:
                - tag: component
                  value: status
"@

$targetIfType = "key: 'net.if.type[ifType.{#SNMPINDEX}]'"
$idx = $content.IndexOf($targetIfType)
if ($idx -gt 0) {
    # Find preceding item prototype marker "            - uuid:"
    $prevItemIdx = $content.LastIndexOf("`n            - uuid:", $idx)
    if ($prevItemIdx -gt 0) {
        $content = $content.Substring(0, $prevItemIdx) + "`n" + $adminStatusBlock + $content.Substring($prevItemIdx)
        Write-Host "Injected Administrative status item prototype before net.if.type."
    }
}

# 8. Add CPU utilization item under items:
$cpuItemBlock = @"
        - uuid: REPLACE_CPU_ITEM_UUID
          name: 'CPU utilization'
          type: SNMP_AGENT
          snmp_oid: 1.3.6.1.4.1.11.2.1.8.0
          key: system.cpu.util
          delay: 1m
          value_type: FLOAT
          units: '%'
          description: |
            MIB: HPE-rndMng / STATISTICS-MIB / RADLAN
            CPU utilization for the last 1 minute on Aruba Instant On 1930 switch.
          tags:
            - tag: component
              value: cpu
          triggers:
            - uuid: REPLACE_CPU_TRIGGER_UUID
              expression: 'min(/Aruba Instant On 1930 by SNMP/system.cpu.util,5m)>{`$CPU.UTIL.CRIT}'
              name: 'High CPU utilization'
              opdata: 'Current utilization: {ITEM.LASTVALUE1}'
              priority: WARNING
              description: 'The CPU utilization is too high. The system might be slow to respond.'
              tags:
                - tag: scope
                  value: performance
"@

$uptimeHwTarget = "name: 'Uptime (hardware)'"
$uptimeHwIdx = $content.IndexOf($uptimeHwTarget)
if ($uptimeHwIdx -gt 0) {
    # Find preceding "- uuid:"
    $prevUuidIdx = $content.LastIndexOf("        - uuid:", $uptimeHwIdx)
    if ($prevUuidIdx -gt 0) {
        $content = $content.Substring(0, $prevUuidIdx) + $cpuItemBlock + "`n" + $content.Substring($prevUuidIdx)
        Write-Host "Injected CPU utilization item."
    }
}

# 9. Add {$CPU.UTIL.CRIT} and {$MEMORY.UTIL.MAX} to macros
$newMacros = @"
        - macro: '{`$CPU.UTIL.CRIT}'
          value: '85'
          description: 'Warning threshold for CPU utilization in %.'
        - macro: '{`$MEMORY.UTIL.MAX}'
          value: '85'
          description: 'Warning threshold for Memory utilization in %.'
"@
$content = $content.Replace("      macros:`n", "      macros:`n$newMacros`n")
Write-Host "Injected CPU and Memory macros."

# 10. Regenerate ALL UUIDs with new UUID v4 (32-hex, no dashes)
# We preserve the group uuid 36bff6c29af64692839d077febfc7079 so it stays in Templates/Network devices
$content = $content.Replace("REPLACE_ADMIN_STATUS_UUID", [System.Guid]::NewGuid().ToString("N"))
$content = $content.Replace("REPLACE_CPU_ITEM_UUID", [System.Guid]::NewGuid().ToString("N"))
$content = $content.Replace("REPLACE_CPU_TRIGGER_UUID", [System.Guid]::NewGuid().ToString("N"))

$groupUuid = "36bff6c29af64692839d077febfc7079"
$uuidRegex = [System.Text.RegularExpressions.Regex]"uuid:\s*([a-f0-9]{32})"
$matches = $uuidRegex.Matches($content)
$uuidMap = @{}

foreach ($m in $matches) {
    $old = $m.Groups[1].Value
    if ($old -ne $groupUuid -and -not $uuidMap.ContainsKey($old)) {
        $uuidMap[$old] = [System.Guid]::NewGuid().ToString("N")
    }
}

Write-Host "Regenerating $($uuidMap.Count) unique UUIDs to avoid any collision..."
foreach ($old in $uuidMap.Keys) {
    $new = $uuidMap[$old]
    $content = $content.Replace($old, $new)
}

# Convert back to standard CRLF
$finalContent = $content -replace "\n", "`r`n"
[System.IO.File]::WriteAllText("$pwd\$dstFile", $finalContent, [System.Text.Encoding]::UTF8)
Write-Host "Successfully generated optimized template at $dstFile (Length: $($finalContent.Length) chars)"
